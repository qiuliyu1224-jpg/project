print("\n🏷️ 立场分类...")

PRO_CN = ["国产", "支持国产", "支持国货", "国货", "文心一言", "通义千问", "中国AI"]
PRO_FOREIGN = ["国外", "外国", "chatgpt", "openai", "gpt-4", "国外技术"]

def classify_stance(text):
    """立场分类"""
    if not text:
        return "中性"
    text_lower = text.lower()

    has_cn = any(kw.lower() in text_lower for kw in PRO_CN)
    has_foreign = any(kw.lower() in text_lower for kw in PRO_FOREIGN)

    if has_cn and not has_foreign:
        return "正面_国产更好"
    elif has_foreign and not has_cn:
        return "负面_外国更好"
    else:
        return "中性"

stance_udf = udf(classify_stance, StringType())
